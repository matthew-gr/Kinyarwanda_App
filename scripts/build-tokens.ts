// Generates src/theme/tokens.css from the design system's tokens.json.
// Run with `npm run tokens` (Node 22.18+ runs TypeScript directly).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

interface Token {
  name: string;
  value: string;
}
interface TypeStyle {
  name: string;
  family?: string;
  fontSize: string;
  lineHeight: number;
  fontWeight: number;
}
interface Tokens {
  color: { tokens: Token[] };
  type: {
    families: Record<string, string>;
    groups: { name: string; family: string; styles: TypeStyle[] }[];
  };
  spacing: { tokens: Token[] };
  radius: { tokens: Token[] };
  shadow: { tokens: Token[] };
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'design-system/tokens.json');
const out = resolve(root, 'src/theme/tokens.css');

function buildTokensCss(tokens: Tokens): string {
  const vars = (list: Token[]) => list.map((t) => `  --${t.name}: ${t.value};`);
  const families = Object.entries(tokens.type.families).map(([k, v]) => `  --font-${k}: ${v};`);

  const styles = tokens.type.groups.flatMap((g) =>
    g.styles.map((s) =>
      [
        `.${s.name} {`,
        `  font-family: var(--font-${s.family ?? g.family});`,
        `  font-size: ${s.fontSize};`,
        `  line-height: ${s.lineHeight};`,
        `  font-weight: ${s.fontWeight};`,
        `  letter-spacing: 0;`,
        `}`,
      ].join('\n'),
    ),
  );

  return [
    '/* Generated by scripts/build-tokens.ts from design-system/tokens.json. Do not edit by hand. */',
    '',
    ':root {',
    '  /* Colour */',
    ...vars(tokens.color.tokens),
    '',
    '  /* Type families */',
    ...families,
    '',
    '  /* Spacing */',
    ...vars(tokens.spacing.tokens),
    '',
    '  /* Radius */',
    ...vars(tokens.radius.tokens),
    '',
    '  /* Shadow */',
    ...vars(tokens.shadow.tokens),
    '}',
    '',
    '/* Text styles */',
    styles.join('\n\n'),
    '',
  ].join('\n');
}

const tokens = JSON.parse(readFileSync(src, 'utf8')) as Tokens;
writeFileSync(out, buildTokensCss(tokens));
console.log(`Wrote ${out}`);
